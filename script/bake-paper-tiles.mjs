#!/usr/bin/env node
/**
 * Bake the upstream paper texture tiles (PNG data URIs from
 * looseleaf src/lib/ink/textures-paper.generated.ts) into a wxss chunk that
 * common/ink consumers inline via `/* @ll-import paper-tiles *\/`.
 *
 *   npm run bake:paper-tiles
 *
 * Emits packages/ui/src/common/style/paper-tiles.wxss with the paper tooth
 * tiles (fibre 240, relief 192 / slip 128, cloud 720), defined on .ll-card so
 * component-scoped styles can see them.
 */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import url from 'node:url';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UPSTREAM = '/Users/panmenglin/github/looseleaf';

const require = createRequire(path.join(UPSTREAM, 'package.json'));
// Node >= 23 strips types on import, but not under node_modules — copy to a
// plain temp dir instead.
const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'll-paper-tiles-')), 'paper-tiles.generated.ts');
fs.copyFileSync(path.join(UPSTREAM, 'src/lib/ink/textures-paper.generated.ts'), tmp);
const mod = await import(url.pathToFileURL(tmp).href);

const { PAPER_FIBRE, PAPER_RELIEF, PAPER_SLIP, PAPER_KRAFT, PAPER_CLOUD } = mod;
const out = `/* generated by script/bake-paper-tiles.mjs from upstream
   src/lib/ink/textures-paper.generated.ts — do not edit
   (.ll-face consumers: sheet components like ll-tag render their stock face
   as CSS — see common/ink.js faceCss) */
.ll-card,
.ll-face {
  --ll-tex-fibre: url("${PAPER_FIBRE.uri}");
  --ll-tex-relief: url("${PAPER_RELIEF.uri}");
  --ll-tex-slip: url("${PAPER_SLIP.uri}");
  --ll-tex-kraft: url("${PAPER_KRAFT.uri}");
  --ll-tex-cloud: url("${PAPER_CLOUD.uri}");
}
`;

const dest = path.join(root, 'packages/ui/src/common/style/paper-tiles.wxss');
fs.writeFileSync(dest, out);
console.log(
  `✓ paper tiles -> ${path.relative(root, dest)} (fibre ${Math.round(PAPER_FIBRE.bytes / 1024)}KB, relief ${Math.round(PAPER_RELIEF.bytes / 1024)}KB, slip ${Math.round(PAPER_SLIP.bytes / 1024)}KB, cloud ${Math.round(PAPER_CLOUD.bytes / 1024)}KB)`,
);
