/**
 * Bundle the upstream looseleaf ink engine into the ui package:
 *
 *   npm run build:ink
 *
 * Emits two artifacts:
 *  - packages/ui/src/common/ink-engine.js  — minified ESM engine
 *    ({ RECIPES, runRecipe, bucketBox }), tree-shaken to the recipes listed
 *    in script/ink-entry.ts
 *  - packages/ui/src/common/tokens.js      — upstream --ll-* paint tokens as
 *    a plain object, used to resolve var(--ll-*) inside runtime-generated SVG
 *
 * Run-time rendering (common/ink.js) draws each component's ink at its real
 * size — replacing the static PNG bake (script/bake-ink.mjs, deleted), which
 * stretched one 360x72 raster and visibly thinned strokes / squared corners
 * at other widths.
 */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UPSTREAM = '/Users/panmenglin/github/looseleaf';

const require = createRequire(path.join(UPSTREAM, 'package.json'));
// esbuild is a transitive dep in the upstream repo's pnpm store — resolve it there.
const esbuildPnpm = fs
  .readdirSync(path.join(UPSTREAM, 'node_modules/.pnpm'))
  .find((d) => d.startsWith('esbuild@'));
const esbuild = require(path.join(UPSTREAM, 'node_modules/.pnpm', esbuildPnpm, 'node_modules/esbuild'));

const { resolveTokens } = await import('./lib/upstream-tokens.mjs');

await esbuild.build({
  entryPoints: [path.join(root, 'script/ink-entry.ts')],
  outfile: path.join(root, 'packages/ui/src/common/ink-engine.js'),
  bundle: true,
  format: 'esm',
  target: ['es2018'],
  minify: true,
  legalComments: 'none',
  tsconfig: path.join(root, 'script/ink-tsconfig.json'),
  logLevel: 'warning',
});

const outEngine = path.join(root, 'packages/ui/src/common/ink-engine.js');
console.log(`✓ ink engine -> ${path.relative(root, outEngine)} (${Math.round(fs.statSync(outEngine).size / 1024)} KB)`);

// --- tokens as JS -----------------------------------------------------------
const tokens = resolveTokens();
const obj = Object.fromEntries(tokens);
const outTokens = path.join(root, 'packages/ui/src/common/tokens.js');
fs.writeFileSync(
  outTokens,
  `/** BUILD ARTIFACT — generated by script/bundle-ink.mjs. Upstream --ll-* paint tokens (light theme). */\nexport default ${JSON.stringify(obj, null, 1)};\n`,
);
console.log(`✓ tokens -> ${path.relative(root, outTokens)} (${Math.round(fs.statSync(outTokens).size / 1024)} KB, ${tokens.size} tokens)`);
