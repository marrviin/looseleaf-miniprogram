/**
 * Subset upstream Kevin Sans (Regular + Bold) and emit it as a base64 JS
 * module so the library can self-load the hand font via wx.loadFontFace.
 *
 *   npm run build:font
 *
 * WeChat's loadFontFace accepts data URIs, which keeps the library
 * self-contained (no CDN requirement). We subset to Latin + common
 * punctuation to keep the module small; CJK text falls back to the system
 * font, exactly as upstream falls back for non-Latin glyphs.
 *
 * Upstream renders the hand face with `size-adjust: 88%` ("Kevin Sans Hand");
 * loadFontFace cannot express size-adjust, so the family is registered as
 * plain "Kevin Sans" at full metrics.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = '/Users/panmenglin/github/looseleaf/src/styles/fonts';
const OUT = path.join(root, 'packages/ui/src/common/font.js');

const UNICODES = 'U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2026,U+20AC';

const WEIGHTS = [
  { file: 'KevinSans-Regular.woff2', weight: 400 },
  { file: 'KevinSans-Bold.woff2', weight: 700 },
];

const parts = WEIGHTS.map(({ file, weight }) => {
  const subset = path.join(root, '.tmp', `subset-${weight}.woff2`);
  fs.mkdirSync(path.dirname(subset), { recursive: true });
  execFileSync('pyftsubset', [
    path.join(SRC_DIR, file),
    `--unicodes=${UNICODES}`,
    '--flavor=woff2',
    `--output-file=${subset}`,
    // keep hinting off / drop layout tables we don't need
    '--no-hinting',
    '--desubroutinize',
    '--name-IDs=',
  ]);
  const b64 = fs.readFileSync(subset).toString('base64');
  console.log(`✓ Kevin Sans ${weight}: ${Math.round(b64.length / 1024)} KB base64`);
  return { weight, b64 };
});

const body = `/**
 * BUILD ARTIFACT — generated by script/build-font.mjs. Do not edit.
 * Kevin Sans (upstream looseleaf hand font), subset to Latin + punctuation,
 * base64 woff2. Loaded once via wx.loadFontFace by common/font.js.
 */
const FACES = [
${parts.map((p) => `  { weight: ${p.weight}, data: 'data:font/woff2;base64,${p.b64}' },`).join('\n')}
];
export default FACES;
`;
fs.writeFileSync(OUT, body);
console.log(`✓ wrote ${path.relative(root, OUT)} (${Math.round(fs.statSync(OUT).size / 1024)} KB)`);
