#!/usr/bin/env node
/**
 * Bake upstream looseleaf design tokens into packages/ui/src/common/style/tokens.wxss.
 *
 * All var()/color-mix() expressions are pre-evaluated to static values
 * (see script/lib/upstream-tokens.mjs) because WXSS cannot rely on color-mix().
 * Values are emitted on `page` so they inherit into every component; the
 * `.dark` / density variants of the upstream theme are out of scope for now
 * (light theme only) — see PLAN.md §3.
 *
 * Run: npm run bake:tokens
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveTokens } from './lib/upstream-tokens.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'packages/ui/src/common/style/tokens.wxss');

const tokens = resolveTokens();

// Split into base palette (--ll-*) and shadcn-style semantic aliases.
const base = [...tokens.entries()].filter(([k]) => k.startsWith('--ll-'));
const alias = [...tokens.entries()].filter(([k]) => !k.startsWith('--ll-'));

const decls = (entries) => entries.map(([k, v]) => `  ${k}: ${v};`).join('\n');

const banner = `/**
 * Looseleaf design tokens — BUILD ARTIFACT, do not edit.
 * Generated by \`npm run bake:tokens\` from upstream looseleaf.css
 * (color-mix()/var() pre-evaluated to static values; light theme).
 */`;

const wxss = `${banner}
page {
${decls(base)}

  /* shadcn-style semantic aliases */
${decls(alias)}
}
`;

fs.writeFileSync(OUT, wxss);
console.log(`✓ wrote ${OUT} (${tokens.size} tokens, ${wxss.length} bytes)`);
